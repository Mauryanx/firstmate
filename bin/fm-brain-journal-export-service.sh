#!/usr/bin/env bash
# fm-brain-journal-export-service.sh - the daily schedule for the brain journal export.
#
# Renders fm-brain-journal-export.service and fm-brain-journal-export.timer,
# systemd --user units that run `fm-brain-desk.py journal-export` for one home
# with the explicit FM_HOME and the FM_BRAIN_DESK_ENABLED=1 opt-in the export
# requires. The timer fires daily at 03:45 UTC, ahead of the brain rooms'
# 04:05 UTC journal, and is Persistent=true, so a run missed while the user
# manager was down happens as soon as it starts again. The service is a oneshot
# that is not retried: a refused export leaves the unit failed, visible in
# `systemctl --user status`, until the next scheduled run replaces it. It runs
# as the user whose manager loads it - install it as the Firstmate account -
# with NoNewPrivileges=yes and no User=, capability or path grant of its own,
# so the export reads and writes exactly what that account already can.
#
# The units name this checkout's absolute paths and FM_HOME as selected when
# rendered. Enabling the timer is the activation step, so install never runs
# systemctl; docs/configuration.md "Brain-room client" owns the activation,
# reinstallation and rollback runbook.
#
# Usage:
#   fm-brain-journal-export-service.sh render service|timer
#       print that unit on stdout
#   fm-brain-journal-export-service.sh install
#       write both units to ${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user/
#       (mode 0644, atomic replace) and print their paths, service first
# FM_HOME (default: this checkout) must be an existing absolute directory.
# Paths with characters outside [A-Za-z0-9._/@+_-] are refused rather than escaped for systemd.
# Exit 0 on success, 1 on a refused path or failed write, 2 on usage.
set -eu

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
NAME=fm-brain-journal-export

die() {
  printf 'fm-brain-journal-export-service.sh: %s\n' "$*" >&2
  exit 1
}

usage() {
  sed -n '/^# Usage:/,/^# Exit/s/^# \{0,1\}//p' "${BASH_SOURCE[0]}"
}

checked_path() {
  case "$1" in
    /*) ;;
    *) die "$2 must be an absolute path: $1" ;;
  esac
  [[ "$1" =~ ^[A-Za-z0-9._/@+_-]+$ ]] || die "$2 has characters this unit does not escape: $1"
  [ -d "$1" ] || die "$2 is not a directory: $1"
}

render() {
  local home=${FM_HOME:-$ROOT}
  checked_path "$ROOT" 'the Firstmate checkout'
  checked_path "$home" FM_HOME
  [ -x "$ROOT/bin/fm-brain-desk.py" ] || die "no executable export at $ROOT/bin/fm-brain-desk.py"
  printf '# Generated by %s/bin/fm-brain-journal-export-service.sh; re-run its install rather than editing.\n' "$ROOT"
  case "$1" in
    service) cat <<EOF
[Unit]
Description=Firstmate brain journal-input export for $home
Documentation=file://$ROOT/docs/configuration.md

[Service]
Type=oneshot
Environment=FM_HOME=$home
Environment=FM_BRAIN_DESK_ENABLED=1
WorkingDirectory=$home
ExecStart=$ROOT/bin/fm-brain-desk.py journal-export
NoNewPrivileges=yes
EOF
      ;;
    timer) cat <<EOF
[Unit]
Description=Daily Firstmate brain journal-input export before the 04:05 UTC journal
Documentation=file://$ROOT/docs/configuration.md

[Timer]
OnCalendar=*-*-* 03:45:00 UTC
Persistent=true
Unit=$NAME.service

[Install]
WantedBy=timers.target
EOF
      ;;
  esac
}

install_units() {
  local dir="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user" kind unit tmp
  local service timer
  service=$(render service) || exit 1
  timer=$(render timer) || exit 1
  mkdir -p "$dir" || die "cannot create $dir"
  for kind in service timer; do
    if [ "$kind" = service ]; then unit=$service; else unit=$timer; fi
    tmp=$(mktemp "$dir/.$NAME.$kind.XXXXXX") || die "cannot write in $dir"
    if ! printf '%s\n' "$unit" > "$tmp" || ! chmod 0644 "$tmp" || ! mv -f "$tmp" "$dir/$NAME.$kind"; then
      rm -f "$tmp"
      die "could not install $dir/$NAME.$kind"
    fi
  done
  printf '%s\n' "$dir/$NAME.service" "$dir/$NAME.timer"
}

case "${1:-}" in
  render)
    [ "$#" -eq 2 ] || { usage >&2; exit 2; }
    case "$2" in service|timer) render "$2" ;; *) usage >&2; exit 2 ;; esac
    ;;
  install) [ "$#" -eq 1 ] || { usage >&2; exit 2; }; install_units ;;
  -h|--help|help) usage ;;
  *) usage >&2; exit 2 ;;
esac
