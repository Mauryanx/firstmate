#!/usr/bin/env bash
# fm-courier-pickup-service.sh - the supervised launcher for bin/fm-courier-pickup.py.
#
# Renders fm-courier-pickup.service, a systemd --user unit that runs
# `fm-courier-pickup.py run` for one home with the explicit FM_HOME and the
# FM_NOTIFY_COURIER=1 opt-in the pickup requires. It is wanted by
# default.target, so an enabled unit starts with the user's manager, which
# starts at boot only when the account lingers (loginctl enable-linger), and
# systemd restarts it 5 s after any failure exit or crash. It runs as the user
# whose manager loads it - install it as the Firstmate account - with
# NoNewPrivileges=yes and no User=, capability or path grant of its own, so the
# pickup reads exactly what that account already can.
#
# The unit names this checkout's absolute paths, resolved when it is rendered,
# so re-run install after moving the checkout or changing FM_HOME rather than
# editing the file. The running pickup keeps its loaded code until the unit is
# restarted. Enabling the unit is the courier activation step, so install never
# runs systemctl; docs/voice-relay.md owns the enable, update and rollback
# runbook.
#
# Usage:
#   fm-courier-pickup-service.sh render    print the unit on stdout
#   fm-courier-pickup-service.sh install   write it to
#       ${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user/fm-courier-pickup.service
#       (mode 0644, atomic replace) and print that path
# FM_HOME (default: this checkout) must be an existing absolute directory.
# Paths with characters outside [A-Za-z0-9._/@+_-] are refused rather than escaped for systemd.
# Exit 0 on success, 1 on a refused path or failed write, 2 on usage.
set -eu

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
UNIT=fm-courier-pickup.service

die() {
  printf 'fm-courier-pickup-service.sh: %s\n' "$*" >&2
  exit 1
}

usage() {
  sed -n '/^# Usage:/,/^# Exit/s/^# \{0,1\}//p' "${BASH_SOURCE[0]}"
}

checked_path() {
  case "$1" in
    /*) ;;
    *) die "$2 must be an absolute path: $1" ;;
  esac
  [[ "$1" =~ ^[A-Za-z0-9._/@+_-]+$ ]] || die "$2 has characters this unit does not escape: $1"
  [ -d "$1" ] || die "$2 is not a directory: $1"
}

render() {
  local home=${FM_HOME:-$ROOT}
  checked_path "$ROOT" 'the Firstmate checkout'
  checked_path "$home" FM_HOME
  [ -x "$ROOT/bin/fm-courier-pickup.py" ] || die "no executable pickup at $ROOT/bin/fm-courier-pickup.py"
  cat <<EOF
# Generated by $ROOT/bin/fm-courier-pickup-service.sh; re-run its install rather than editing.
[Unit]
Description=Firstmate courier iMessage pickup for $home
Documentation=file://$ROOT/docs/voice-relay.md

[Service]
Type=simple
Environment=FM_HOME=$home
Environment=FM_NOTIFY_COURIER=1
WorkingDirectory=$home
ExecStart=$ROOT/bin/fm-courier-pickup.py run
Restart=on-failure
RestartSec=5
NoNewPrivileges=yes

[Install]
WantedBy=default.target
EOF
}

install_unit() {
  local dir="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user" unit tmp
  unit=$(render) || exit 1
  mkdir -p "$dir" || die "cannot create $dir"
  tmp=$(mktemp "$dir/.$UNIT.XXXXXX") || die "cannot write in $dir"
  if ! printf '%s\n' "$unit" > "$tmp" || ! chmod 0644 "$tmp" || ! mv -f "$tmp" "$dir/$UNIT"; then
    rm -f "$tmp"
    die "could not install $dir/$UNIT"
  fi
  printf '%s\n' "$dir/$UNIT"
}

case "${1:-}" in
  render) [ "$#" -eq 1 ] || { usage >&2; exit 2; }; render ;;
  install) [ "$#" -eq 1 ] || { usage >&2; exit 2; }; install_unit ;;
  -h|--help|help) usage ;;
  *) usage >&2; exit 2 ;;
esac
